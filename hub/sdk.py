    def list_templates(self) -> list[dict]:
        templates_dir = self.sdk_dir / "templates"
        if not templates_dir.exists():
            return []
        return [{"id": d.name, "name": d.name.replace("-", " ").title(),
                 "path": str(d)} for d in templates_dir.iterdir() if d.is_dir()]

    def init_project(self, project_type: str, name: str, author: str = "",
                     description: str = "", path: str = "") -> dict:
        template_dir = self.sdk_dir / "templates" / project_type
        if not template_dir.exists():
            return {"success": False, "error": f"Template '{project_type}' not found"}
        if not name:
            return {"success": False, "error": "Name required"}
        if not path:
            path = os.path.join(os.getcwd(), name)
        target = Path(path)
        if target.exists():
            return {"success": False, "error": f"Path already exists: {path}"}
        author = author or "Aetheros Developer"
        description = description or f"{name} plugin for AetherOS"
        snake = name.lower().replace(" ", "_").replace("-", "_")
        npm = name.lower().replace(" ", "-").replace("_", "-")

        def render(template: str) -> str:
            return (template.replace("{{name}}", name)
                    .replace("{{description}}", description)
                    .replace("{{author}}", author)
                    .replace("{{snake_name}}", snake)
                    .replace("{{npm_name}}", npm))

        shutil.copytree(str(template_dir), str(target))
        for root, dirs, files in os.walk(str(target)):
            for fn in files:
                fp = Path(root) / fn
                content = fp.read_text(encoding="utf-8")
                if "{{" in content:
                    fp.write_text(render(content), encoding="utf-8")

        project = SDKProject(project_type=project_type, name=name,
                             language="python", path=str(target))
        logger.info("Created %s project at %s", project_type, path)
        return {"success": True, "project_type": project_type, "name": name,
                "path": path, "files": len(list(target.rglob("*")))}

    def build(self, project_path: str, output_path: str = "") -> dict:
        project = Path(project_path)
        if not project.exists():
            return {"success": False, "error": f"Project not found: {project_path}"}
        if not output_path:
            output_path = os.path.join(project_path, "dist", f"{project.name}.aetheros")
        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)

        package_files = ["manifest.json", "plugin.py", "server.py",
                         "index.js", "theme.yaml", "config.yaml",
                         "workflow.json", "README.md"]
        with zipfile.ZipFile(str(output), "w", zipfile.ZIP_DEFLATED) as zf:
            for root, dirs, files in os.walk(str(project)):
                for fn in files:
                    fp = Path(root) / fn
                    rel = str(fp.relative_to(project))
                    if rel.startswith("dist") or rel.startswith("__pycache__"):
                        continue
                    if rel.startswith(".git") or rel.startswith("node_modules"):
                        continue
                    zf.write(str(fp), rel)
        logger.info("Built package: %s", output)
        return {"success": True, "output": str(output),
                "size": output.stat().st_size}

    def package(self, project_path: str, output_path: str = "") -> dict:
        return self.build(project_path, output_path)

    def publish(self, package_path: str, registry: str = "local") -> dict:
        pkg = Path(package_path)
        if not pkg.exists():
            return {"success": False, "error": f"Package not found: {package_path}"}
        registry_dir = get_aetheros_home() / "hub" / "published"
        registry_dir.mkdir(parents=True, exist_ok=True)
        dest = registry_dir / pkg.name
        shutil.copy2(str(pkg), str(dest))
        logger.info("Published %s to %s", pkg.name, registry)
        return {"success": True, "path": str(dest), "registry": registry}

    def get_sdk_version(self) -> str:
        return "1.0.0"
