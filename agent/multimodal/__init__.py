"""AetherOS Universal Multimodal Perception & Interaction OS — core layer.

Implements Master Prompt 10 as a **library** that wraps production Aetheros
systems (vision/OCR/document/audio/video/screen tools, the models.dev catalog,
the transport registry).  It is deliberately NOT wired into run_agent's hot
loop: per AGENTS.md the core is a narrow waist, so this layer is invoked by
CLI commands, service-gated tools, and plugins.

Modules:
- media_abstraction  : normalized MediaObject (Phase 1)
- input_router       : file/URL/base64/text/structured -> MediaObject (Phase 2)
- capability_detector: per-model modality detection (Phase 3)
- enhanced_routing   : modality-aware model selection (Phase 4)
- perception         : routes MediaObjects to production tools (Phases 5-45)
- context_builder    : assembles multimodal context (Phase 53)
- stream_manager     : bounded media streams + backpressure (Phases 48-52)
- privacy_router     : sensitivity classification + provider routing (71-74)
- provenance         : evidence + grounding + hallucination defense (57-65)
- security           : adversarial media / prompt-injection defense (66-70)
- memory             : multimodal memory + RAG references (54-56)
- api                : stable media.* API surface (Phase 91)
- fusion             : cross-modal fusion engine (Phases 19-25)
- local_models       : local multimodal models + offline mode (Phases 73-74)
"""

