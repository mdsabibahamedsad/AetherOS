use serde::{Deserialize, Serialize};
use std::path::PathBuf;

use crate::setup_wizard::WizardState;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GenerationResult {
    pub success: bool,
    pub config_written: bool,
    pub profile_written: bool,
    pub secrets_stored: bool,
    pub workspace_created: bool,
    pub errors: Vec<String>,
}

fn aetheros_home() -> PathBuf {
    crate::paths::aetheros_home()
}

pub fn generate_all(wizard: &WizardState) -> GenerationResult {
    let mut errors = Vec::new();
    let mut config_written = false;
    let mut profile_written = false;
    let mut secrets_stored = false;
    let mut workspace_created = false;

    // 1. Write config.yaml
    match generate_config_yaml(wizard) {
        Ok(()) => config_written = true,
        Err(e) => errors.push(format!("Config: {e}")),
    }

    // 2. Write user profile
    match generate_profile(wizard) {
        Ok(()) => profile_written = true,
        Err(e) => errors.push(format!("Profile: {e}")),
    }

    // 3. Store encrypted secrets
    match store_secrets(wizard) {
        Ok(()) => secrets_stored = true,
        Err(e) => errors.push(format!("Secrets: {e}")),
    }

    // 4. Create workspace
    match create_workspace_structure(wizard) {
        Ok(()) => workspace_created = true,
        Err(e) => errors.push(format!("Workspace: {e}")),
    }

    // 5. Generate default agent config
    if let Err(e) = generate_agent_config(wizard) {
        errors.push(format!("Agent config: {e}"));
    }

    GenerationResult {
        success: errors.is_empty(),
        config_written,
        profile_written,
        secrets_stored,
        workspace_created,
        errors,
    }
}

fn generate_config_yaml(wizard: &WizardState) -> Result<(), String> {
    let config_path = aetheros_home().join("config").join("config.yaml");
    if let Some(parent) = config_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("Cannot create config dir: {e}"))?;
    }

    let profile_name = wizard.profile.as_ref().map(|p| p.display_name.as_str()).unwrap_or("default");
    let workspace_name = wizard.profile.as_ref().map(|p| p.workspace_name.as_str()).unwrap_or("My Workspace");
    let language = wizard.profile.as_ref().map(|p| p.language.as_str()).unwrap_or("en-US");
    let theme = wizard.theme.as_ref().map(|t| t.mode.as_str()).unwrap_or("system");

    let mut provider_section = String::new();
    if let Some(ref model_sel) = wizard.models {
        let default_model = model_sel.default_model.as_str();
        let reasoning_model = model_sel.reasoning_model.as_deref().unwrap_or("");
        let coding_model = model_sel.coding_model.as_deref().unwrap_or("");
        let vision_model = model_sel.vision_model.as_deref().unwrap_or("");

        let provider_id = wizard.ai_providers.first().map(|p| p.provider.as_str()).unwrap_or("");
        provider_section = format!(
            r##"
model:
  provider: "{}"
  model: "{}"
  reasoning_model: "{}"
  coding_model: "{}"
  vision_model: "{}"
"##,
            provider_id, default_model, reasoning_model, coding_model, vision_model
        );
    }

    let content = format!(
        r##"# AetherOS Configuration
# Generated by Setup Wizard

profile:
  name: "{}"
  workspace: "{}"
  language: "{}"

display:
  theme: "{}"
  skin: "default"

logging:
  level: "info"
{}"##,
        profile_name, workspace_name, language, theme, provider_section
    );

    std::fs::write(&config_path, &content)
        .map_err(|e| format!("Cannot write config.yaml: {e}"))?;

    tracing::info!("config.yaml generated");
    Ok(())
}

fn generate_profile(wizard: &WizardState) -> Result<(), String> {
    let profile_dir = aetheros_home().join("profiles").join("default");
    std::fs::create_dir_all(&profile_dir)
        .map_err(|e| format!("Cannot create profile dir: {e}"))?;

    let display_name = wizard.profile.as_ref().map(|p| p.display_name.as_str()).unwrap_or("User");
    let workspace_name = wizard.profile.as_ref().map(|p| p.workspace_name.as_str()).unwrap_or("My Workspace");
    let language = wizard.profile.as_ref().map(|p| p.language.as_str()).unwrap_or("en-US");
    let region = wizard.profile.as_ref().map(|p| p.region.as_str()).unwrap_or("US");
    let timezone = wizard.profile.as_ref().map(|p| p.timezone.as_str()).unwrap_or("UTC");

    let content = format!(
        r##"profile:
  name: "{}"
  workspace: "{}"
  language: "{}"
  region: "{}"
  timezone: "{}"
  created_at: {}
  version: "{}"
"##,
        display_name, workspace_name, language, region, timezone,
        now_secs(),
        env!("CARGO_PKG_VERSION")
    );

    std::fs::write(profile_dir.join("profile.yaml"), &content)
        .map_err(|e| format!("Cannot write profile: {e}"))?;

    tracing::info!("user profile generated");
    Ok(())
}

fn store_secrets(wizard: &WizardState) -> Result<(), String> {
    for config in &wizard.api_configs {
        if !config.api_key.is_empty() {
            let key_name = format!("ai_provider_{}", config.provider);
            crate::encryptor::store_secret(&key_name, &config.api_key)?;

            if let Some(org_id) = &config.organization_id {
                if !org_id.is_empty() {
                    let org_key = format!("ai_provider_{}_org", config.provider);
                    crate::encryptor::store_secret(&org_key, org_id)?;
                }
            }
        }
    }

    for service in &wizard.services {
        if service.enabled {
            if let Some(config) = &service.config {
                if let Some(token_val) = config.get("token") {
                    if let Some(token) = token_val.as_str() {
                        let key = format!("service_token_{}", service.service);
                        crate::encryptor::store_secret(&key, token)?;
                    }
                }
            }
        }
    }

    tracing::info!("secrets stored securely");
    Ok(())
}

fn create_workspace_structure(_wizard: &WizardState) -> Result<(), String> {
    let dirs = vec![
        "projects",
        "knowledge",
        "downloads",
        "extensions",
        "logs",
        "models",
        "cache",
    ];

    for dir in &dirs {
        let path = aetheros_home().join(dir);
        std::fs::create_dir_all(&path)
            .map_err(|e| format!("Cannot create {dir}: {e}"))?;
    }

    tracing::info!("workspace structure created");
    Ok(())
}

fn generate_agent_config(wizard: &WizardState) -> Result<(), String> {
    let agent_dir = aetheros_home().join("config");
    let agent_config_path = agent_dir.join("agent.yaml");

    let max_iterations = 90;
    let theme = wizard.theme.as_ref().map(|t| t.mode.as_str()).unwrap_or("system");

    let content = format!(
        r##"# AetherOS Agent Configuration
agent:
  max_iterations: {}
  quiet_mode: true

display:
  theme: "{}"
  skin: "default"

terminal:
  shell: ""

logging:
  level: "info"
"##,
        max_iterations, theme
    );

    std::fs::write(&agent_config_path, &content)
        .map_err(|e| format!("Cannot write agent config: {e}"))?;

    Ok(())
}

fn now_secs() -> String {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
        .to_string()
}

#[tauri::command]
pub async fn generate_setup_configuration(wizard_state: WizardState) -> Result<GenerationResult, String> {
    let result = generate_all(&wizard_state);
    if result.success {
        crate::first_run::mark_wizard_complete()?;
    }
    Ok(result)
}
