from aetheros_platform.errors import err
from aetheros_platform.schemas import validate

TRUSTED_SERVERS: set = set()


def validate_server_manifest(manifest: Dict[str, Any]) -> List[str]:
    return validate("MCPServer", manifest)


def mark_trusted(name: str) -> None:
    TRUSTED_SERVERS.add(name)


def is_trusted(name: str) -> bool:
    return name in TRUSTED_SERVERS


SERVER_TEMPLATE = '''"""Generated by `aetheros-platform mcp init {name}` (MCP SDK)."""
import os
import sys

try:
    from mcp.server.fastmcp import FastMCP
except ImportError:
    print("the 'mcp' package is required: pip install mcp", file=sys.stderr)
    raise SystemExit(2)

mcp = FastMCP("{name}")


@mcp.tool()
def hello(name: str = "developer") -> str:
    """Say hello (structured string result)."""
    return "hello " + name


@mcp.resource("info://server")
def server_info() -> str:
    """Server metadata resource."""
    return "{name} v{version} (transport: stdio)"


@mcp.prompt()
def greet() -> str:
    """Example prompt."""
    return "Greet the developer warmly."


if __name__ == "__main__":
    mcp.run()
'''

MANIFEST_TEMPLATE = """name: {name}
version: {version}
transport: stdio
command: python server.py
tools: [hello]
"""


def mcp_init(dest: Path, name: str, version: str = "1.0.0") -> Dict[str, Any]:
    """Scaffold a real runnable MCP server project."""
    dest = Path(dest)
    (dest).mkdir(parents=True, exist_ok=True)
    (dest / "server.py").write_text(SERVER_TEMPLATE.format(name=name, version=version))
    (dest / "manifest.yaml").write_text(MANIFEST_TEMPLATE.format(name=name, version=version))
    (dest / "README.md").write_text(f"# {name}\n\nMCP server (stdio). Run: `python server.py`.\n")
    (dest / "test_server.py").write_text(
        "import subprocess, sys, json\n"
        "proc = subprocess.run([sys.executable, 'server.py', '--help'], capture_output=True, text=True, timeout=30)\n"
        "assert proc.returncode in (0, 2), proc.stderr[:500]\n"
        "print('server entrypoint ok')\n")
    manifest = {"name": name, "version": version, "transport": "stdio",
                "command": "python server.py", "tools": ["hello"]}
    errors = validate_server_manifest(manifest)
    assert not errors, errors
    return {"path": str(dest), "manifest": manifest, "valid": True}


async def list_tools_stdio(server_path: str, timeout_s: float = 30.0) -> List[Dict[str, Any]]:
    """Real protocol exchange: spawn the server over stdio, negotiate,
    list tools. Used by contract tests (no fakes)."""
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client
    params = StdioServerParameters(command="python", args=[server_path])
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            tools = await session.list_tools()
            return [{"name": t.name, "description": t.description or "",
                     "inputSchema": t.inputSchema} for t in tools.tools]


async def call_tool_stdio(server_path: str, tool: str, args: Dict[str, Any],
                          timeout_s: float = 30.0) -> Any:
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client
    params = StdioServerParameters(command="python", args=[server_path])
    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            await session.initialize()
            result = await session.call_tool(tool, args)
            out = []
            for block in result.content or []:
                if hasattr(block, "text"):
                    out.append(block.text)
                else:
                    out.append(str(block))
            return {"content": out, "isError": bool(getattr(result, "isError", False))}
