def cmd_init(args) -> int:
    kind, name = args.kind, args.name
    dest = Path(args.dest or ".") / name
    dest.mkdir(parents=True, exist_ok=True)
    if kind == "agent":
        (dest / "agent.py").write_text(AGENT_TEMPLATE.format(name=name))
        (dest / "test_agent.py").write_text(AGENT_TEST_TEMPLATE)
        manifest = {"name": name, "version": "1.0.0",
                    "description": "Reference agent.",
                    "capabilities": ["artifact.create", "memory.read"],
                    "tools": ["echo"]}
    elif kind == "tool":
        (dest / "tool.py").write_text(TOOL_TEMPLATE.format(name=name))
        manifest = {"name": name, "version": "1.0.0", "kind": "tool",
                    "aetherosVersion": ">=1.0.0"}
        (dest / "manifest.json").write_text(json.dumps(manifest, indent=2))
        (dest / "README.md").write_text(f"# {name}\n\nRun: `aetheros-platform test --project .`\n")
        print(f"created {dest}")
        return 0
    elif kind == "skill":
        (dest / "skill.py").write_text(SKILL_TEMPLATE.format(name=name, tool="echo"))
        manifest = {"name": name, "version": "1.0.0",
                    "description": "Example skill.", "capabilities": ["artifact.create"],
                    "tools": ["echo"], "dependencies": {}}
    elif kind == "mcp":
        from aetheros_platform import mcp as _mcp
        out = _mcp.mcp_init(dest, name)
        print(f"created MCP server at {out['path']} (valid={out['valid']})")
        return 0
    elif kind == "a2a":
        (dest / "agent_card.json").write_text(json.dumps(
            {"name": name, "version": "1.0.0", "protocolVersion": "0.3.0-compat",
             "description": "A2A reference agent.", "capabilities": ["artifact.create"],
             "endpoint": "http://127.0.0.1:8765/api/v1/a2a",
             "authentication": {"type": "api-key"}, "trust": "untrusted"}, indent=2))
        manifest = {"name": name, "version": "1.0.0", "kind": "agent",
                    "aetherosVersion": ">=1.0.0"}
    elif kind == "extension":
        manifest = {"name": name, "version": "1.0.0", "kind": "extension",
                    "aetherosVersion": ">=1.0.0",
                    "permissions": [], "entrypoints": {"main": "extension.py"}}
        (dest / "extension.py").write_text('"""Extension entrypoint."""\n')
    else:
        print(f"unknown kind {kind}", file=sys.stderr)
        return 2
    if kind in ("agent", "skill"):
        (dest / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (dest / "README.md").write_text(f"# {name}\n\nRun: `aetheros-platform test --project .`\n")
    (dest / "policy.yaml").write_text("default: deny\nallow: [artifact.create, memory.read]\n")
    print(f"created {dest}")
    return 0


def cmd_schema(args) -> int:
    from aetheros_platform import schemas as _s
    if args.ts:
        from aetheros_platform import tsgen
        print(tsgen.generate(), end="")
    elif args.name:
        _print(_s.SCHEMAS.get(args.name, {}))
    else:
        _print({"schemaVersion": _s.SCHEMA_VERSION, "schemas": sorted(_s.SCHEMAS)})
    return 0


def cmd_api(args) -> int:
    from aetheros_platform import registry as _r
    if args.api_action == "list":
        _print(_r.public_endpoints())
    elif args.api_action == "serve":
        import uvicorn
        from aetheros_platform.gateway import create_app
        print(f"serving developer API on {args.bind}:{args.port} (LOCAL DEVELOPMENT ONLY)")
        uvicorn.run(create_app(), host=args.bind, port=args.port)
    return 0


def cmd_test(args) -> int:
    import subprocess
    proj = Path(args.project or ".")
    tests = sorted(proj.glob("test_*.py")) + sorted(proj.glob("tests/test_*.py"))
    if not tests:
        print("no tests found in project (add test_*.py)")
        return 1
    failures = 0
    for t in tests:
        r = subprocess.run([sys.executable, "-m", "pytest", str(t), "-q",
                            "-p", "no:cacheprovider", "-o", "addopts="],
                           capture_output=True, text=True, timeout=120)
        print(f"--- {t}: {'PASS' if r.returncode == 0 else 'FAIL'}")
        if r.returncode != 0:
            failures += 1
            print(r.stdout[-2000:])
    return 1 if failures else 0


def cmd_package(args) -> int:
    from aetheros_platform import packages as _p
    if args.pkg_action == "build":
        _print(_p.build_package(Path(args.project or ".")))
    elif args.pkg_action == "publish":
        _print(_p.publish(Path(args.file)))
    elif args.pkg_action == "install":
        _print(_p.install(args.name, args.version, Path(args.dest or ".")))
    return 0


def cmd_auth(args) -> int:
    from aetheros_platform.auth import APIKeyManager
    mgr = APIKeyManager()
    if args.auth_action == "key-create":
        _print(mgr.create(args.name, (args.scopes or "").split(",") if args.scopes else [],
                          owner=args.owner or ""))
    elif args.auth_action == "key-list":
        _print(mgr.list())
    elif args.auth_action == "key-revoke":
        _print({"revoked": mgr.revoke(args.key_id)})
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="aetheros-platform")
    sub = p.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("init")
    g.add_argument("kind", choices=["agent", "skill", "tool", "mcp", "a2a", "extension"])
    g.add_argument("name")
    g.add_argument("--dest", default=None)
    g.set_defaults(func=cmd_init)

    g = sub.add_parser("dev")
    g.add_argument("--port", type=int, default=8765)
    g.add_argument("--bind", default="127.0.0.1")
    g.set_defaults(func=lambda a: cmd_api(
        type("A", (), {"api_action": "serve", "bind": a.bind, "port": a.port})()))

    g = sub.add_parser("schema")
    g.add_argument("--name", default=None)
    g.add_argument("--ts", action="store_true")
    g.set_defaults(func=cmd_schema)

    g = sub.add_parser("api")
    g.add_argument("api_action", choices=["list", "serve"])
    g.add_argument("--bind", default="127.0.0.1")
    g.add_argument("--port", type=int, default=8765)
    g.set_defaults(func=cmd_api)

    g = sub.add_parser("test")
    g.add_argument("--project", default=".")
    g.set_defaults(func=cmd_test)

    g = sub.add_parser("package")
    g.add_argument("pkg_action", choices=["build", "publish", "install"])
    g.add_argument("--project", default=".")
    g.add_argument("--file", default=None)
    g.add_argument("--name", default=None)
    g.add_argument("--version", default=None)
    g.add_argument("--dest", default=None)
    g.set_defaults(func=cmd_package)

    g = sub.add_parser("auth")
    g.add_argument("auth_action", choices=["key-create", "key-list", "key-revoke"])
    g.add_argument("--name", default="dev-key")
    g.add_argument("--scopes", default="")
    g.add_argument("--owner", default="")
    g.add_argument("--key-id", default=None)
    g.set_defaults(func=cmd_auth)

    args = p.parse_args(argv)
    try:
        return args.func(args)
    except Exception as exc:
        from aetheros_platform.errors import AetherError
        if isinstance(exc, AetherError):
            print(json.dumps(exc.to_dict(), indent=2))
            return 1
        raise


if __name__ == "__main__":
    raise SystemExit(main())
