"""Documentation generator — API/CLI/schema references from code (§52).

`python -m aetheros_platform.docgen --out docs` regenerates:
- AETHEROS_API_REFERENCE.md (from registry.ENDPOINTS)
- AETHEROS_SCHEMA_REFERENCE.md (from schemas.SCHEMAS)
- AETHEROS_DEVELOPER_CLI.md (from cli.py parser + live --help capture)
Only documents what exists; stability/experimental flags are preserved.
"""

from __future__ import annotations

import argparse
from pathlib import Path


def api_reference() -> str:
    from aetheros_platform import registry as _r
    from aetheros_platform import schemas as _s
    lines = ["# AetherOS Developer API Reference",
             "",
             f"Registry version `{_r.REGISTRY_VERSION}`, "
             f"schema version `{_s.SCHEMA_VERSION}`.",
             "",
             "| Method | Endpoint | Stability | Auth | Scopes | Rate | "
             "Input | Output | Idempotent | Streaming |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for e in _r.ENDPOINTS:
        lines.append(
            f"| {e['method']} | `{e['endpoint']}` | {e['stability']} | "
            f"{e['authentication']} | {', '.join(e['scopes']) or '—'} | "
            f"{e['rateLimit']} | {e['inputSchema'] or '—'} | "
            f"{e['outputSchema'] or '—'} | "
            f"{'yes' if e['idempotency'] else 'no'} | "
            f"{'yes' if e['streaming'] else 'no'} |")
    lines += ["",
              "## Versioning",
              "",
              "See `AETHEROS_API_VERSIONING.md`. `/api/v2` currently serves "
              "as an alias of v1 with `Sunset: not-planned` headers; "
              "breaking changes require a new registry version plus a "
              "6-month deprecation notice.",
              "",
              "## Errors",
              "",
              "Every failure returns a typed `AetherError` body "
              "(`code/category/message/retryable/remediation/...`). "
              "See `AETHEROS_DEVELOPER_SECURITY.md` for the category table.",
              ""]
    return "\n".join(lines)


def schema_reference() -> str:
    from aetheros_platform import schemas as _s
    import json
    lines = ["# AetherOS Schema Reference",
             "",
             f"Schema version `{_s.SCHEMA_VERSION}` — single source of truth "
             "in `aetheros_platform/schemas.py`. TypeScript bindings are "
             "generated by `aetheros_platform/tsgen.py` (never hand-edited).",
             ""]
    for name in sorted(_s.SCHEMAS):
        schema = _s.SCHEMAS[name]
        req = schema.get("required", [])
        props = schema.get("properties", {})
        lines.append(f"## `{name}`")
        lines.append("")
        lines.append(f"Required: {', '.join(f'`{r}`' for r in req) or '—'}")
        lines.append("")
        for prop, spec in props.items():
            typ = spec.get("type", "any")
            extra = ""
            if "enum" in spec:
                extra = f" (one of: {', '.join(map(str, spec['enum'][:8]))})"
            if "pattern" in spec:
                extra += f" (pattern `{spec['pattern'][:60]}`)"
            lines.append(f"- `{prop}`: {typ}{extra}")
        lines.append("")
    lines.append("_Full JSON Schemas: `GET /api/v1/schemas`._")
    lines.append("")
    return "\n".join(lines)


def cli_reference() -> str:
    import io
    from contextlib import redirect_stdout
    lines = ["# AetherOS Developer CLI Reference",
             "",
             "Standalone developer CLI: `python -m aetheros_platform.cli`.",
             "Only commands that actually work are exposed.",
             "",
             "> NOTE: integration into the main `aetheros` binary is BLOCKED "
             "by a pre-existing startup crash (`conflicting subparser: "
             "agent` from `aetheros_cli/agent_network_cmd.py:34` vs "
             "`agents/cli.py:445`). The standalone CLI below is the real, "
             "tested developer surface.",
             ""]
    cmds = [
        (["init", "--help"], "init"),
        (["dev", "--help"], "dev"),
        (["schema", "--help"], "schema"),
        (["api", "--help"], "api"),
        (["test", "--help"], "test"),
        (["package", "--help"], "package"),
        (["auth", "--help"], "auth"),
    ]
    import sys
    sys.path.insert(0, ".")
    from aetheros_platform.cli import main as _main
    for argv, name in cmds:
        buf = io.StringIO()
        try:
            with redirect_stdout(buf):
                _main(argv)
        except SystemExit:
            pass
        lines += [f"## `{name}`", "", "```", buf.getvalue().strip(), "```", ""]
    lines += ["### Workflows",
              "",
              "```bash",
              "# five minutes to a running agent",
              "export PYTHONPATH=$PWD AETHEROS_HOME=$PWD/.dev-home",
              "python -m aetheros_platform.cli auth key-create --name dev "
              "--scopes agents:write,tasks:write,tasks:read --owner me",
              "python -m aetheros_platform.cli dev --port 8765  # local gateway",
              "python -m aetheros_platform.cli init agent my-agent --dest .",
              "python -m aetheros_platform.cli test --project my-agent",
              "```",
              ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="docs")
    a = p.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "AETHEROS_API_REFERENCE.md").write_text(api_reference())
    (out / "AETHEROS_SCHEMA_REFERENCE.md").write_text(schema_reference())
    (out / "AETHEROS_DEVELOPER_CLI.md").write_text(cli_reference())
    print("wrote API + schema + CLI references to", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
